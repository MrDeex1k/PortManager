"""Generate wire types from core models and desktop responses."""

import argparse
import json
import os
import subprocess
import sys
import types
from pathlib import Path
from typing import Literal, Union, get_args, get_origin, get_type_hints

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from portscanner.core import model  # noqa: E402

MODELS = [
    model.DockerPort,
    model.TunnelRoute,
    model.TunnelInfo,
    model.ServiceTag,
    model.ProcessInfo,
    model.KubernetesPort,
    model.PortEntry,
    model.LocalIP,
    model.SourceReport,
]


def python_type(tp):
    """Translate supported core annotations into Python payload type expressions."""
    origin, args = get_origin(tp), get_args(tp)
    if origin in (types.UnionType, Union):
        return " | ".join(python_type(arg) for arg in args)
    if origin is Literal:
        return "Literal[" + ", ".join(repr(arg) for arg in args) + "]"
    if origin is tuple:
        return "tuple[" + python_type(args[0]) + ", ...]"
    if tp is type(None):
        return "None"
    return tp.__name__ + ("Payload" if tp in MODELS else "")


def core_python():
    """Generate TypedDict payloads, including the GUI row identifier."""
    text = (
        "# Generated by scripts/generate_contracts.py; do not edit.\n"
        "from typing import Literal, TypedDict\n\n"
    )
    for cls in MODELS:
        text += f"\nclass {cls.__name__}Payload(TypedDict):\n"
        for field, tp in get_type_hints(cls).items():
            text += f"    {field}: {python_type(tp)}\n"
        if cls is model.PortEntry:
            text += "    id: str\n"
        text += "\n"
    return text


def ts_name(name):
    return {"PortEntry": "PortRow"}.get(
        name.removesuffix("Payload"), name.removesuffix("Payload")
    )


def ts_type(tp):
    """Translate supported Python annotations into TypeScript wire types."""
    origin, args = get_origin(tp), get_args(tp)
    if origin in (types.UnionType, Union):
        return " | ".join(ts_type(arg) for arg in args)
    if origin is Literal:
        return " | ".join(
            json.dumps(arg) if not isinstance(arg, bool) else str(arg).lower()
            for arg in args
        )
    if origin in (tuple, list):
        return f"Array<{ts_type(args[0])}>"
    if tp in (int, float):
        return "number"
    if tp is str:
        return "string"
    if tp is bool:
        return "boolean"
    if tp is type(None):
        return "null"
    return ts_name(tp.__name__)


def typescript():
    """Generate core and bridge interfaces while preserving optional response keys."""
    from portscanner.gui import contracts

    text = "// Generated by scripts/generate_contracts.py; do not edit.\n"
    for cls in [*MODELS, *contracts.RESPONSES]:
        text += f"export interface {ts_name(cls.__name__)} {{\n"
        optional = getattr(cls, "__optional_keys__", set())
        for field, tp in get_type_hints(cls).items():
            text += f"  {field}{'?' if field in optional else ''}: {ts_type(tp)}\n"
        if cls is model.PortEntry:
            text += "  id: string\n"
        text += "}\n"
    return text


def casefold_typescript():
    """Generate Unicode casefold exceptions relative to lowercase conversion."""
    exceptions = {
        chr(i): chr(i).casefold()
        for i in range(0x110000)
        if chr(i).casefold() != chr(i).lower()
    }
    return (
        "// Generated by scripts/generate_contracts.py; do not edit.\n"
        "const exceptions: Record<string, string> = "
        + json.dumps(exceptions, ensure_ascii=True)
        + "\nexport function casefold(value: string): string {\n"
        "  return Array.from(value, (char) => "
        "exceptions[char] ?? char.toLowerCase()).join('')\n"
        "}\n"
    )


def format_ts(content):
    """Format generated TypeScript using the installed frontend Prettier."""
    return subprocess.run(
        ["bun", "--bun", "prettier", "--stdin-filepath", "src/contracts.generated.ts"],
        cwd=ROOT / "frontend",
        input=content,
        text=True,
        capture_output=True,
        check=True,
    ).stdout


def outputs():
    """Format all generated files in memory for comparison or writing."""
    python = subprocess.run(
        [
            str(
                Path(sys.executable).with_name(
                    "ruff.exe" if os.name == "nt" else "ruff"
                )
            ),
            "format",
            "--stdin-filename",
            "core_payloads.py",
            "-",
        ],
        input=core_python(),
        text=True,
        capture_output=True,
        check=True,
    ).stdout

    return {
        ROOT / "portscanner/gui/core_payloads.py": python,
        ROOT / "frontend/src/contracts.generated.ts": format_ts(typescript()),
        ROOT / "frontend/src/casefold.ts": format_ts(casefold_typescript()),
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--bootstrap", action="store_true")
    args = parser.parse_args()
    if args.bootstrap:
        (ROOT / "portscanner/gui/core_payloads.py").write_text(core_python())
    else:
        for path, content in outputs().items():
            if args.check:
                if path.read_text() != content:
                    raise SystemExit(f"Outdated contract: {path}")
            else:
                path.write_text(content)
